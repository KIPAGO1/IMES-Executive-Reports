@Injectable({providedIn:'root'})
export class TranslationService {
  readonly language = signal<Language>(this.restore());
  private restore(): Language {
    try { return localStorage.getItem('imes-language') === 'en' ? 'en' : 'sw'; }
    catch { return 'sw'; }
  }
  setLanguage(value: string): void {
    const language: Language = value === 'en' ? 'en' : 'sw';
    this.language.set(language);
    try { localStorage.setItem('imes-language', language); } catch {}
    document.documentElement.lang = language;
  }
  t(key: string): string { return translations[this.language()][key] ?? key; }
}
